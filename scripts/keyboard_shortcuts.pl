#!/usr/bin/env perl
# keyboard_shortcuts.pl - generate the keyboard shortcut cheat sheet.
#
# The shortcuts live in help.pl, beside the prose they belong to, so an app's
# own Help page and this sheet are always the same words. This script writes
# them out as Markdown for printing or for reading away from the screen.
#
#   perl scripts/keyboard_shortcuts.pl            # rewrite docs/KEYBOARD-SHORTCUTS.md
#   perl scripts/keyboard_shortcuts.pl --check    # exit 1 when the file is stale
#
# Run it after changing any topic's shortcut list.
use strict;
use warnings;
use FindBin;
chdir "$FindBin::Bin/.." or die "cannot find the jawnos root: $!";
require './help.pl';

my $check = grep { $_ eq '--check' } @ARGV;
my $path = 'docs/KEYBOARD-SHORTCUTS.md';

my $text = "# JawnOS keyboard shortcuts\n\n";
$text .= "Generated from the Help registry (`help.pl`) by `perl scripts/keyboard_shortcuts.pl`.\n";
$text .= "Do not edit this file by hand: change a topic's shortcut list in `help.pl`, then run the script.\n\n";
$text .= 'Windows move with **Super** - the Windows key on a PC, Command on a Mac. '
	. "An app's keys act only while that app is the front window, and never while the focus is in a text field. "
	. "Press **F1** anywhere for the Help topic of the window in focus.\n\n";

my $rows = 0;
foreach my $group ( &help::shortcut_sheet() ) {
	$text .= '## ' . $group->{'title'} . "\n\n";
	$text .= "| Keys | Action |\n| --- | --- |\n";
	foreach my $row ( @{ $group->{'rows'} } ) {
		my ($keys, $action) = @{$row};
		$keys =~ s/\|/\\|/g;
		$action =~ s/\|/\\|/g;
		$text .= '| `' . $keys . '` | ' . $action . " |\n";
		$rows++;
	}
	$text .= "\n";
}

if ($check) {
	open my $fh, '<', $path or do {
		print "missing: $path (run without --check to write it)\n";
		exit 1;
	};
	local $/;
	my $current = <$fh>;
	close $fh;
	if (defined $current && $current eq $text) {
		print "up to date: $path ($rows shortcuts)\n";
		exit 0;
	}
	print "stale: $path (run without --check to regenerate)\n";
	exit 1;
}

open my $out, '>', "$path.tmp" or die "cannot write $path.tmp: $!";
print $out $text;
close $out or die "cannot close $path.tmp: $!";
rename "$path.tmp", $path or die "cannot move $path.tmp to $path: $!";
print "wrote $path ($rows shortcuts)\n";
